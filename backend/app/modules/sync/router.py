"""
ShiVi Offline Sync & Causal Engine API Router
=============================================

Briefing:
    Core synchronization router implementing ShiVi's bi-directional offline event-sourcing
    pipeline. Field responders capture incidents, route assessments, task updates, and photographic
    evidence entirely offline into local SQLite databases. When any network bearer becomes
    available (BLE mesh relay, Wi-Fi Direct, tactical hotspot, or cellular), the field device
    initiates a batch push/pull sequence.

Reason:
    In disaster response, network connectivity is intermittent, slow, and partitioned.
    Traditional REST APIs (direct POST/PUT on mutable resource endpoints) fail completely because:
    1. Simultaneous edits overwrite each other without a causal trace.
    2. Connection drops midway through requests cause duplicate records or partial state corruption.
    3. Low-bandwidth Bluetooth Low Energy (BLE) channels cannot handle large monolithic HTTP bodies.

Architectural Solutions in this Router:
    - Idempotent Event Push (`/push`): Evaluates unique `event_id` keys against the immutable event
      ledger, guaranteeing exactly-once semantics even across repeated network re-transmissions.
    - Causal Conflict Detection: Automatically detects concurrent contradictions on life-safety
      fields (e.g. USABLE vs BLOCKED), freezes entities into `UNCERTAIN` state, locks dependent
      tasks, and generates a formal `ConflictCase` for supervisor adjudication.
    - Cursor-Based Pull (`/pull`): Enables bandwidth-efficient, monotonic delta retrieval so nodes
      only download events received since their last synchronization checkpoint.
    - Omni-Bearer Mesh Packetization (`/mesh/packetize`, `/mesh/reassemble`): Slices arbitrary
      JSON payloads into ≤496-byte BLE 5.0 GATT MTU chunks with CRC32 checksums and reassembles them
      with full SHA-256 payload integrity validation.
"""

