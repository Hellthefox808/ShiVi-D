# Briefing: FastAPI router mounted under `/sync` tag for all offline replication workflows.
# Reason: Centralizes event-sourcing ingestion and mesh packetization endpoints.
router = APIRouter(prefix="/sync", tags=["Offline Sync & Causal Engine"])


class EventChange(BaseModel):
    """
    Briefing:
        Represents a field-level delta transition within an event envelope.

    Reason:
        Retains both the prior base value (what the client observed when making the edit)
        and the new proposed value, enabling three-way merge evaluation and causal auditing.
    """
    # Explanation: Prior state observed by the client (None if creating entity)
    base: Optional[Any] = None
    # Explanation: New target state proposed by the mutation
    new: Any


class EventEnvelopeIn(BaseModel):
    """
    Briefing:
        Pydantic representation of an inbound event envelope generated by a mobile edge node.

    Reason:
        Encapsulates all metadata required to enforce distributed consistency, multi-bearer routing,
        and tamper verification (device sequence number, Lamport version vector, relay hop counter,
        and SHA-256 cryptographic integrity hash).
    """
    # Explanation: Deterministic UUIDv4 generated locally by the originating device
    event_id: str
    # Explanation: Tenant organization identifier
    tenant_id: str
    # Explanation: Entity domain ('incident', 'task', 'route_observation', 'evidence')
    entity_type: str
    # Explanation: UUID of the specific target entity
    entity_id: str
    # Explanation: Action type ('CREATED', 'STATUS_CHANGED', 'NOTE_ADDED', etc.)
    event_type: str
    # Explanation: Dictionary of field-level changes (e.g. {"status": {"base": "OPEN", "new": "BLOCKED"}})
    changes: Dict[str, EventChange]
    # Explanation: User UUID of the responder who authorized the action
    actor_id: str
    # Explanation: Hardware device ID that recorded the observation
    device_id: str
    # Explanation: Monotonically increasing sequence number per device for replay detection
    device_sequence: int
    # Explanation: Physical UTC timestamp when the event occurred in the field
    occurred_at: datetime
    # Explanation: Lamport or vector clock mapping device_id -> logical sequence
    version_vector: Dict[str, int] = {}
    # Explanation: List of UUIDs pointing to uploaded cryptographic photo evidence
    evidence_ids: List[str] = []
    # Explanation: Number of mesh hops traversed prior to reaching this server
    relay_hops: int = 0
    # Explanation: Trace of relaying device IDs along the multi-hop mesh path
    relayed_by_devices: List[str] = []
    # Explanation: Primary physical bearer used ('BLE_MESH', 'WIFI_DIRECT', 'CELLULAR', 'DIRECT')
    initial_bearer: Optional[str] = "DIRECT"
    # Explanation: Schema version of the event format (default 1)
    schema_version: int = 1
    # Explanation: SHA-256 digest computed across payload fields for tamper-evidence
    integrity_hash: str


class SyncPushBatch(BaseModel):
    """
    Briefing:
        Batch container submitted by field nodes during synchronization push.

    Reason:
        Allows field devices to upload accumulated outbox queues in an atomic HTTP transaction.
    """
    # Explanation: Originating device hardware identifier
    device_id: str
    # Explanation: Ordered array of event envelopes to ingest
    events: List[EventEnvelopeIn]


class SyncPushResult(BaseModel):
    """
    Briefing:
        Structured response returned after processing a batch of synchronization events.

    Reason:
        Informs the mobile client which event IDs were accepted (allowing the client to mark
        them as synced in its local outbox), which were identified as duplicates, how many
        conflicts were detected, and provides the server's updated cursor timestamp.
    """
    status: str = "success"
    processed_count: int
    accepted_event_ids: List[str]
    duplicate_event_ids: List[str]
    conflicts_detected: int
    server_cursor: str


class SyncPullResult(BaseModel):
    """
    Briefing:
        Payload returned when a client requests downstream events from the server.

    Reason:
        Supplies incremental events received by other field units, enabling the client
        to update its local SQLite database and advance its replication cursor.
    """
    events: List[Dict[str, Any]]
    next_cursor: str
    has_more: bool


@router.post("/push", response_model=SyncPushResult)
async def push_sync_events(
    batch: SyncPushBatch,
    db: AsyncSession = Depends(get_db),
    current_user: TokenPayload = Depends(get_current_user_token),
):
    """
    Briefing:
        Processes an uploaded batch of offline event envelopes into the server's event ledger.

    Reason:
        1. Guarantees Idempotency: Checks `OperationalEvent` table by `event_id`. Duplicates are
           skipped without error, enabling safe client retries across unreliable links.
        2. Preserves Immutable Audit Trail: Appends accepted events into `OperationalEvent` with
           server-side `received_at` UTC timestamps and cryptographic hashes.
        3. Applies Domain State Materialization:
           - Automatically merges non-conflicting metadata (e.g. appending field notes and photo IDs).
           - Enforces the Causal Safety Freeze: If a status change contradicts verified physical reality
             (e.g. route USABLE vs BLOCKED), it halts automated updates, locks the route to `UNCERTAIN`,
             freezes dependent tasks, logs a system `AuditEntry`, and opens a `ConflictCase`.
        4. Cache Invalidation: Invalidates central dashboard aggregates (`IOCCacheManager`) so commanders
           immediately see fresh field telemetry.

    Parameters:
        batch: `SyncPushBatch` containing the list of envelopes.
        db: Database session.
        current_user: Authenticated JWT claims.

    Returns:
        `SyncPushResult` detailing accepted events, duplicates, and conflict count.
    """
    accepted_ids = []
    duplicate_ids = []
    conflicts_count = 0

    for ev in batch.events:
        # Explanation: Step 1 - Idempotency verification to prevent duplicate event ingestion
        existing_res = await db.execute(
            select(OperationalEvent).where(
                OperationalEvent.event_id == ev.event_id,
                OperationalEvent.tenant_id == current_user.tenant_id,
            )
        )
        if existing_res.scalars().first():
            duplicate_ids.append(ev.event_id)
            continue

        # Explanation: Step 2 - Append immutable operational event record to historical ledger
        op_event = OperationalEvent(
            id=str(uuid.uuid4()),
            tenant_id=current_user.tenant_id,
            event_id=ev.event_id,
            entity_type=ev.entity_type,
            entity_id=ev.entity_id,
            event_type=ev.event_type,
            changes={k: {"base": v.base, "new": v.new} for k, v in ev.changes.items()},
            actor_id=ev.actor_id,
            device_id=ev.device_id,
            device_sequence=ev.device_sequence,
            occurred_at=ev.occurred_at,
            received_at=datetime.now(timezone.utc),
            version_vector=ev.version_vector,
            evidence_ids=ev.evidence_ids,
            integrity_hash=ev.integrity_hash,
        )
        db.add(op_event)
        accepted_ids.append(ev.event_id)

        # Explanation: Step 3 - Domain Entity Materialization & Contradiction Evaluation
        if ev.entity_type == "route_observation":
            route_id = ev.entity_id
            r_res = await db.execute(
                select(RouteObservation).where(
                    RouteObservation.route_identifier == route_id,
                    RouteObservation.tenant_id == current_user.tenant_id,
                )
            )
            route = r_res.scalars().first()
            if not route:
                # Explanation: Lazily instantiate route observation entity if first report
                route = RouteObservation(
                    id=str(uuid.uuid4()),
                    tenant_id=current_user.tenant_id,
                    route_identifier=route_id,
                    status="UNKNOWN",
                    notes=[],
                    photos=[],
                )
                db.add(route)

            # Explanation: Safe Additive Metadata - notes are merged without conflict
            if "notes" in ev.changes:
                new_note = ev.changes["notes"].new
                current_notes = list(route.notes or [])
                if isinstance(new_note, list):
                    current_notes.extend(new_note)
                elif new_note and new_note not in current_notes:
                    current_notes.append(new_note)
                route.notes = current_notes

            # Explanation: Safe Additive Metadata - photographic evidence IDs are accumulated
            if "photos" in ev.changes or ev.evidence_ids:
                current_photos = list(route.photos or [])
                for pid in ev.evidence_ids:
                    if pid not in current_photos:
                        current_photos.append(pid)
                route.photos = current_photos

            # Explanation: Protected Life-Safety Attribute Handling (Route Status)
            if "status" in ev.changes:
                new_status = str(ev.changes["status"].new).upper()
                old_status = str(route.status).upper()

                if old_status not in ["UNKNOWN", "UNCERTAIN"] and old_status != new_status:
                    # Explanation: Concurrency contradiction detected! Trigger safety freeze!
                    conflicts_count += 1
                    
                    # Explanation: Create persistent Conflict Case for human supervisor adjudication
                    conflict_case = ConflictCase(
                        id=str(uuid.uuid4()),
                        tenant_id=current_user.tenant_id,
                        entity_type="route_observation",
                        entity_id=route_id,
                        conflicting_field="status",
                        status="OPEN",
                        claims=[
                            {
                                "actor_id": route.last_reported_by or "prior_responder",
                                "device_id": "prior_device",
                                "value": old_status,
                                "occurred_at": route.last_reported_at.isoformat() if route.last_reported_at else datetime.utcnow().isoformat(),
                            },
                            {
                                "actor_id": ev.actor_id,
                                "device_id": ev.device_id,
                                "value": new_status,
                                "occurred_at": ev.occurred_at.isoformat(),
                                "evidence_ids": ev.evidence_ids,
                            },
                        ],
                        frozen_dependencies=[],
                    )
                    
                    # Explanation: Freeze route into UNCERTAIN state to prevent misleading responders
                    route.status = "UNCERTAIN"
                    route.is_frozen = "TRUE"
                    route.active_conflict_id = conflict_case.id

                    # Explanation: Freeze dependent rescue tasks utilizing this route segment
                    t_res = await db.execute(
                        select(Task).where(
                            Task.route_id == route_id,
                            Task.tenant_id == current_user.tenant_id,
                        )
                    )
                    frozen_task_ids = []
                    for t in t_res.scalars().all():
                        t.is_route_blocked = "TRUE"
                        frozen_task_ids.append(t.id)
                    conflict_case.frozen_dependencies = frozen_task_ids
                    
                    db.add(conflict_case)

                    # Explanation: Protected immutable audit log entry
                    audit = AuditEntry(
                        id=str(uuid.uuid4()),
                        tenant_id=current_user.tenant_id,
                        action="CONFLICT_DETECTED_FREEZE",
                        actor_id="system_conflict_engine",
                        actor_role="SYSTEM",
                        target_entity_type="route_observation",
                        target_entity_id=route_id,
                        previous_state={"status": old_status},
                        new_state={"status": "UNCERTAIN", "conflict_id": conflict_case.id},
                        reason=f"Life-safety contradiction: {old_status} vs {new_status}. Automation frozen.",
                    )
                    db.add(audit)
                else:
                    # Explanation: Non-conflicting status progression applies cleanly
                    route.status = new_status
                    route.last_reported_by = ev.actor_id
                    route.last_reported_at = ev.occurred_at

            await db.flush()

    await db.commit()

    # Explanation: Invalidate cached operational summaries so command dashboards reflect fresh events
    from app.modules.dashboard.router import IOCCacheManager
    IOCCacheManager.invalidate(current_user.tenant_id)

    return SyncPushResult(
        status="success",
        processed_count=len(batch.events),
        accepted_event_ids=accepted_ids,
        duplicate_event_ids=duplicate_ids,
        conflicts_detected=conflicts_count,
        server_cursor=datetime.now(timezone.utc).isoformat(),
    )


@router.get("/pull", response_model=SyncPullResult)
async def pull_sync_events(
    cursor: Optional[str] = None,
    limit: int = 50,
    db: AsyncSession = Depends(get_db),
    current_user: TokenPayload = Depends(get_current_user_token),
):
    """
    Briefing:
        Retrieves an incremental page of downstream operational events newer than a given cursor.

    Reason:
        Allows field devices to efficiently synchronize without downloading the entire database.
        Devices supply their last recorded `cursor` (UTC ISO string). The server queries
        `received_at > cursor` ordered chronologically, returning up to `limit` events.

    Parameters:
        cursor: Optional ISO-8601 UTC timestamp representing client's current sync watermark.
        limit: Maximum number of events to return in a single page (default 50).
        db: Database session.
        current_user: Authenticated JWT claims.

    Returns:
        `SyncPullResult` containing event list, `next_cursor`, and `has_more` boolean.
    """
    query = select(OperationalEvent).where(
        OperationalEvent.tenant_id == current_user.tenant_id
    )
    if cursor:
        try:
            dt = datetime.fromisoformat(cursor)
            query = query.where(OperationalEvent.received_at > dt)
        except Exception:
            pass

    query = query.order_by(OperationalEvent.received_at.asc()).limit(limit)
    result = await db.execute(query)
    events = result.scalars().all()

    formatted = [
        {
            "event_id": e.event_id,
            "entity_type": e.entity_type,
            "entity_id": e.entity_id,
            "event_type": e.event_type,
            "changes": e.changes,
            "actor_id": e.actor_id,
            "device_id": e.device_id,
            "occurred_at": e.occurred_at.isoformat(),
            "received_at": e.received_at.isoformat(),
            "evidence_ids": e.evidence_ids,
            "integrity_hash": e.integrity_hash,
        }
        for e in events
    ]

    next_cur = events[-1].received_at.isoformat() if events else (cursor or datetime.now(timezone.utc).isoformat())

    return SyncPullResult(
        events=formatted,
        next_cursor=next_cur,
        has_more=len(events) == limit,
    )


